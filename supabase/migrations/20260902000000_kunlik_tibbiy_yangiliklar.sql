  ON public.bannerlar(yangilik_id, target_role);

-- Rol ajratilishi faqat UI filtriga bog'liq qolmaydi.
DROP POLICY IF EXISTS "Faol bannerlarni hamma ko'ra oladi" ON public.bannerlar;
DROP POLICY IF EXISTS "bannerlar_select" ON public.bannerlar;
DROP POLICY IF EXISTS "rolga_mos_faol_bannerlar" ON public.bannerlar;
CREATE POLICY "rolga_mos_faol_bannerlar" ON public.bannerlar
  FOR SELECT USING (
    faol = true AND arxiv = false
    AND (boshlanish IS NULL OR boshlanish <= now())
    AND (tugash IS NULL OR tugash >= now())
    AND (
      target_role IS NULL OR target_role = 'hamma'
      OR (auth.uid() IS NULL AND target_role = 'landing')
      OR target_role = (SELECT role FROM public.profiles WHERE id = auth.uid())
    )
  );
