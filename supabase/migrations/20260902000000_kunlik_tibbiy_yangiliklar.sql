DROP POLICY IF EXISTS "published_yangiliklarni_oqish" ON public.yangiliklar;
CREATE POLICY "published_yangiliklarni_oqish" ON public.yangiliklar
  FOR SELECT USING (
    status = 'published'
    OR EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

DROP POLICY IF EXISTS "admin_yangiliklarni_boshqaradi" ON public.yangiliklar;
CREATE POLICY "admin_yangiliklarni_boshqaradi" ON public.yangiliklar
  FOR ALL USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

DROP POLICY IF EXISTS "admin_yangilik_manbalari" ON public.yangilik_manbalari;
