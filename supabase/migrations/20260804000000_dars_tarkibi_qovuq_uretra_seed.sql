    LUT</span>) deb ataladigan tizimning ikki asosiy a'zosidir. Ularning birgalikdagi
    vazifasi — siydikni past bosim ostida saqlash (to'planish/saqlash fazasi) va keyin
    ixtiyoriy ravishda to'liq chiqarib tashlash (chiqarish/bo'shatish fazasi), bularning
    barchasi pasaytirilgan bosim ostida amalga oshadi.
  </p>

  <div class="callout callout--note">
