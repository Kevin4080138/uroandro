<section id="uretra-ayol" class="section">
  <h2><span class="num">5</span>Ayol siydik chiqarish kanali <span class="en-term">female urethra</span></h2>

  <p>
    Ayollarda uretra ancha qisqaroq — uzunligi taxminan <strong>4–5 sm</strong> atrofida
    bo'lib, qov suyagi orqasidan o'tib, oldingi qin devori bo'ylab to'g'ridan-to'g'ri
    tashqariga (vestibulga) ochiladi.
  </p>

  <h3>5.1. Tuzilishi</h3>
  <ul>
    <li><strong>Epiteliy</strong> — o'tish epiteliysi, distal qismida yassi epiteliyga o'tadi;</li>
    <li><strong>Shilliq osti qavati <span class="en-term">submukoza</span></strong> — qon tomirlariga boy, ushlab turish (kontinens)ga hissa qo'shadi;</li>
    <li><strong>Mushak qavati</strong> — ichki uzunlamasiga va tashqi dumaloq silliq mushak qatlamlari.</li>
  </ul>

  <h3>5.2. Sfinkter mexanizmi</h3>
  <p>
    Ayollarda erkaklardagidek to'liq mushak halqasi mavjud emas, lekin
    <strong>uretrovaginal sfinkter</strong> va <strong>pubokoksigeus mushagi</strong>
    kabi tuzilmalar uretraning yopilishiga yordam beradi. Tashqi sfinkter uretraning
    distal ikki uchdan birida joylashgan, ko'ndalang-targ'il mushakdan iborat va
    ixtiyoriy nazoratga ega.
  </p>

  <div class="callout callout--note">
