    qismi (S2–S4) o'rtasidagi murakkab muvofiqlashtirilgan jarayon. Qovuq
    to'lishi haqidagi signal miyaga yetib boradi, va inson ongli ravishda
    siydishni boshlash yoki kechiktirishga qaror qiladi.
  </p>

