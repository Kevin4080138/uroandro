<!-- 2. QOVUQ TUZILISHI -->
<section id="qovuq-tuzilishi" class="section">
  <h2><span class="num">2</span>Qovuqning tuzilishi</h2>

  <h3>2.1. Joylashuvi va umumiy tavsifi</h3>
  <p>
    Qovuq — kattalarda <strong>haqiqiy chanoq (true pelvis)</strong>da joylashgan,
    siydikni vaqtincha to'plovchi mushak-membranali a'zo. U asosan
    <strong>qorin parda tashqarisida (extraperitoneal)</strong> joylashgan, faqat
    yuqori qismi (gumbaz, dome) qorin parda bilan qoplangan.
  </p>
  <p>
    Qovuqning gumbaz qismi <strong>urakus (urachus)</strong> deb ataladigan, embrional
    davrda mavjud bo'lgan naysimon tuzilma bilan davom etadi; bu tuzilma normada
    kindik darajasida yo'qoladi (obliteratsiya).
  </p>

  <h3>2.2. Devor qatlamlari</h3>
  <p>
    Qovuq devori ichkaridan tashqariga qarab quyidagi qatlamlardan iborat:
  </p>
  <ol>
    <li><strong>Urotelium <span class="en-term">urothelium</span></strong> — o'tish epiteliysi, yuza "soyabon hujayralar (umbrella cells)" qatlami bilan;</li>
    <li><strong>Shilliq osti qavati <span class="en-term">lamina propria</span></strong> — biriktiruvchi to'qima, qon tomirlari va nervlarni saqlaydi;</li>
    <li><strong>Detruzor mushagi <span class="en-term">detrusor muscle</span></strong> — uch qavatli silliq mushak (ichki uzunlamasiga, o'rta dumaloq, tashqi uzunlamasiga), siydikni chiqarish uchun muskul kuchini ta'minlaydi.</li>
  </ol>

  <h3>2.3. Uchburchak (trigone) va qovuq bo'yni</h3>
  <p>
    Qovuq ikki funksional jihatdan farqli sohaga bo'linadi: <strong>tana (body)</strong> —
    siydik yo'li teshiklaridan yuqorida joylashgan qism, va <strong>asos (base)</strong> —
    uchburchak (trigone) va qovuq bo'ynidan <span class="en-term">bladder neck</span> iborat.
  </p>
  <ul>
    <li>
      <strong>Uchburchak (trigone)</strong> — ikki siydik yo'li teshigi va qovuq bo'yni
      orasidagi uchburchak shaklidagi soha. Bu — detruzor mushagining eng qalin qismi
      bo'lib, eng ko'p qon bilan ta'minlangan, shu sababli sistoskopiyada atrofdan
      <strong>to'qroq rangda</strong> ko'rinadi.
    </li>
    <li>
      <strong>Qovuq bo'yni <span class="en-term">bladder neck</span></strong> — erkaklarda to'liq, halqasimon
      silliq mushak qatlamiga ega (<strong>ichki siydik sfinkteri, <span class="en-term">internal urethral
      sphincter</span></strong>); ayollarda bunday to'liq halqa mavjud emas.
    </li>
  </ul>

  <div class="callout callout--note">
    <strong class="callout-title">Yo'naltiruvchi</strong>
    Erkaklarda qovuq bo'ynidagi to'liq mushak halqasi jinsiy funksiyada muhim rol
    o'ynaydi — u urug' otish vaqtida yopilib, spermaning orqaga (qovuqqa) qaytib
    ketmasligini ta'minlaydi (antegrad ejakulyatsiya).
  </div>

  <h3>2.4. Buyrak-qovuq qo'shilish nuqtasi (UVJ)</h3>
  <p>
    Siydik yo'li qovuq devoridan <strong>Waldeyer pardasi</strong> bilan o'ralgan holda
    qiyalik bo'ylab o'tadi va trigonega birlashadi. Bu mahkam mushak tutqichi
    siydik to'lganda devor-ichi siydik yo'li qismini siqib, <strong>bir tomonlama
    klapan</strong> vazifasini bajaradi va vezikoureteral reflyuksning oldini oladi.
  </p>
</section>

