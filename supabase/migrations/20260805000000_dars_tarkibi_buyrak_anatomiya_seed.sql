<!-- 5. QON TA'MINOTI -->
<section id="qon" class="section">
  <h2><span class="num">5</span>Buyrakning qon ta'minoti</h2>

  <p>
    Har bir buyrak <strong>buyrak arteriyasi <span class="en-term">renal artery</span></strong> orqali qon bilan
    ta'minlanadi. Bu arteriyalar qorin aortasidan taxminan <strong>L1–L2 umurtqa
    darajasida</strong> juft holda chiqadi.
  </p>

  <h3>5.1. Arterial tarmoqlanish ketma-ketligi</h3>
  <ol>
    <li><strong>Buyrak arteriyasi <span class="en-term">renal artery</span></strong> — buyrak darvozasiga yaqinlashganda segmentar arteriyalarga bo'linadi.</li>
    <li><strong>Segmentar arteriyalar</strong> — buyrak sinusida lobar arteriyalarga bo'linadi.</li>
    <li><strong>Lobar arteriyalar</strong> — parenximaga kirib, interlobar arteriyalarni hosil qiladi (Bertin ustunlari orqali o'tadi).</li>
    <li><strong>Yoysimon arteriyalar <span class="en-term">arcuate arteries</span></strong> — piramidalar asosida, korteks-medulla chegarasida joylashadi.</li>
    <li><strong>Interlobulyar arteriyalar</strong> — korteks ichida radial yo'nalishda tarqaladi va har bir glomerulaga olib boruvchi <strong>afferent arteriolalar</strong>ga bo'linadi.</li>
  </ol>

  <div class="callout callout--warning">
    <strong class="callout-title">Diqqat!</strong>
    Buyrak yon tomonida, old va orqa segmentar arteriyalar orasida nisbatan
    <strong>tomirlarsiz chiziq (Brodel chizig'i, <span class="en-term">line of Brodel</span>)</strong> mavjud. Bu chiziq
    bo'ylab kesim qilinganda qon yo'qotish ancha kamroq bo'ladi — shuning uchun perkutan
    buyrak kirish <span class="en-term">percutaneous renal access</span> va ba'zi jarrohlik kesimlari aynan shu
    chiziq orqali amalga oshiriladi.
  </div>

  <h3>5.2. Variatsiyalar</h3>
  <p>
    Buyrak arteriyalarining soni, kattaligi va joylashuvida sezilarli o'zgaruvchanlik
    mavjud — holatlarning <strong>taxminan to'rtdan bir qismida</strong> qo'shimcha
    (supernumerary) buyrak arteriyalari uchraydi. Bu variatsiya jarrohlik va transplantatsiya
    rejalashtirishda muhim ahamiyatga ega.
  </p>
</section>

