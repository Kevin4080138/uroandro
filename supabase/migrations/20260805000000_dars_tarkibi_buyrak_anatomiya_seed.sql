  <h2><span class="num">3</span>Buyrakning tashqi tuzilishi va qoplamalari</h2>

  <p>
    Buyrak tashqaridan ichkariga qarab quyidagi qoplamalarga ega:
  </p>
  <ol>
    <li><strong>Haqiqiy kapsula <span class="en-term">true capsule</span></strong> — buyrak parenximasiga bevosita yopishgan, yupqa, silliq fibroz parda;</li>
    <li><strong>Perirenal yog' <span class="en-term">perirenal fat</span></strong> — buyrak atrofidagi yog' qatlami, Gerota fastsiyasi ichida joylashgan;</li>
    <li><strong>Gerota fastsiyasi</strong> — buyrak va buyrak usti bezini o'rab turuvchi biriktiruvchi to'qima;</li>
    <li><strong>Paranefrik yog' <span class="en-term">paranephric fat</span></strong> — Gerota fastsiyasidan tashqarida joylashgan qo'shimcha yog' qatlami.</li>
  </ol>

  <h3>O'lchamlari</h3>
  <p>
    Kattalarda har bir buyrak o'rtacha <strong>10–12 sm</strong> uzunlikda bo'ladi. Buyraklar
    nafas olish va tana holati o'zgarishi (yotgan holatdan tik turishga) bilan vertikal
    yo'nalishda taxminan <strong>3 sm</strong> (bir umurtqa tanasi balandligiga teng)
    siljishi mumkin.
  </p>

  <div class="callout callout--note">
    <strong class="callout-title">Yo'naltiruvchi</strong>
    Buyrak o'lchamlarini eslab qolish uchun foydali qiyoslash: bir buyrak taxminan
    <strong>kattalarning musht (mushak)</strong> kattaligiga yaqin, ya'ni 10–12 sm.
    Bu mutlaq qiymat emas, individual farqlar mavjud bo'lishi mumkin.
  </div>
</section>

<!-- 4. ICHKI TUZILISHI -->
<section id="ichki" class="section">
  <h2><span class="num">4</span>Buyrakning ichki (makroskopik va mikroskopik) tuzilishi</h2>

  <h3>4.1. Korteks va medulla</h3>
  <p>
    Buyrakni kesib ko'rilganda ikki aniq sohani ajratish mumkin:
  </p>
  <ul>
    <li><strong>Po'stloq qism <span class="en-term">cortex</span></strong> — tashqi, ochiq rangli soha, taxminan 1 sm qalinlikda;</li>
    <li><strong>Miya qism <span class="en-term">medulla</span></strong> — ichki, to'qroq rangli soha, 8–18 ta konus shaklidagi <strong>buyrak piramidalari <span class="en-term">renal pyramids</span></strong>dan iborat.</li>
  </ul>
  <p>
    Korteks piramidalar orasiga kirib, <strong>Bertin ustunlari <span class="en-term">columns of Bertin</span></strong>ni
    hosil qiladi. Har bir piramidaning uchi <strong>buyrak so'rg'ichi <span class="en-term">renal papilla</span></strong>ni
    tashkil etadi, har bir so'rg'ich bitta <strong>kichik kosacha <span class="en-term">minor calyx</span></strong> bilan
    qoplangan.
  </p>

  <h3>4.2. Siydik to'plovchi tizim <span class="en-term">pelvicalyceal system</span></h3>
  <p>
    Bir nechta kichik kosachalar birlashib <strong>katta kosacha <span class="en-term">major calyx</span></strong>ni
    hosil qiladi, katta kosachalar esa birlashib <strong>buyrak jomi <span class="en-term">renal pelvis</span></strong>ni
    tashkil etadi. Buyrak jomi odatda <strong>3–10 mL</strong> siydik sig'imiga ega.
  </p>

  <div class="callout callout--note">
    <strong class="callout-title">Yodlash uslubi (VAUA)</strong>
    Buyrak darvozasida (hilum) oldindan orqaga qarab joylashuv tartibi:
    <strong>V</strong>ena (renal vein) → <strong>A</strong>rteriya (renal artery) →
    <strong>U</strong>reter/jom (renal pelvis/ureter) → <strong>A</strong>rteriya (orqa segmentar arteriya).
  </div>

  <h3>4.3. Nefron — funksional birlik</h3>
  <p>
    Buyrakning eng kichik funksional birligi — <strong>nefron <span class="en-term">nephron</span></strong>. Har bir
    kattalar buyragida taxminan <strong>0.4–1.2 million nefron</strong> mavjud. Har bir
    nefron <strong>glomerula <span class="en-term">glomerulus</span></strong> — qon tomirlari to'plamidan iborat
    filtratsiya birligi — va uni o'rab turgan <strong>Bowman kapsulasi</strong>dan boshlanadi.
  </p>
  <p>
    Glomerula qonni <strong>125 mL/min</strong> tezlikda filtrlaydi — bu ko'rsatkich
    <strong>glomerulyar filtratsiya tezligi <span class="en-term">GFR</span></strong> deb
    ataladi va buyrak funksiyasining asosiy ko'rsatkichi hisoblanadi. Filtrat keyin proksimal
    kanalcha, Genle qovuzlog'i, distal kanalcha va to'plovchi kanalchalardan o'tib, siydik
    shaklida kosachalarga, so'ngra buyrak jomiga oqib tushadi.
  </p>

