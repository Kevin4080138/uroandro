<!-- 7. KLINIK AHAMIYATI -->
<section id="klinik" class="section">
  <h2><span class="num">7</span>Klinik ahamiyati</h2>

  <h3>7.1. Perkutan kirish bilan bog'liq xavfsizlik</h3>
  <ul>
    <li>
      <strong>Pleura va o'pka shikastlanishi xavfi</strong> — buyrakning yuqori qutubi
      diafragma va ko'krak qafasiga yaqin joylashgan. 11-qovurg'adan yuqorida kirish pleura va o'pkaga shikast yetkazish xavfini oshiradi.
      Shu sababli, imkon qadar <strong>12-qovurg'adan past (subkostal)</strong> yoki
      <strong>11–12-qovurg'alar orasidan</strong> kirish afzal ko'riladi.
    </li>
    <li>
      <strong>Yo'g'on ichak shikastlanishi xavfi</strong> — kamdan-kam hollarda yo'g'on
      ichak buyrakning orqa-pastki qismida joylashishi mumkin <span class="en-term">retrorenal colon</span>, bu esa
      perkutan kirishda ichak shikastlanishi xavfini tug'diradi.
    </li>
  </ul>

  <h3>7.2. Og'riq va innervatsiya</h3>
  <p>
    Buyrak kapsulasi va siydik to'plovchi tizimning cho'zilishi <strong>simpatik nervlar
    orqali</strong> og'riq signalini uzatadi. Bu og'riq odatda <strong>bel/yon qism
    (flank), chov sohasi yoki moshonka/labiya sohasiga</strong> aks etadigan
    (<span class="en-term">referred pain</span>) xususiyatga ega — bu siydik toshi
    og'rig'ining klassik tarqalish yo'nalishini tushuntiradi.
  </p>

  <h3>7.3. Tug'ma anomaliyalar haqida qisqacha</h3>
  <p>
    Yangi tug'ilganlardagi tug'ma anomaliyalarning <strong>20–30%</strong>i buyrak va
    siydik yo'liga tegishli bo'lib, son, burilish, ko'tarilish va/yoki birlashish
    anomaliyalarini o'z ichiga oladi. Bunga misol qilib <strong>siydik yo'li
