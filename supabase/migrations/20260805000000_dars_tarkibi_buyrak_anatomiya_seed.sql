<!-- 1. UMUMIY NAZAR -->
<section id="tarif" class="section">
  <h2><span class="num">1</span>Umumiy nazar</h2>

  <p>
    <strong>Buyrak <span class="en-term">kidney</span></strong> va <strong>siydik yo'li <span class="en-term">ureter</span></strong> — yuqori siydik
    yo'li (<span class="en-term">upper urinary tract</span>) deb ataladigan tizimning asosiy
    a'zolaridir. Ular qorin parda ortidagi maxsus bo'shliqda — <strong>retroperitoneal
    bo'shliq <span class="en-term">retroperitoneum</span></strong>da — joylashgan.
  </p>
  <p>
    "Retroperitoneal" so'zi lotincha <em>retro</em> ("orqada") va <em>peritoneum</em> ("qorin
    parda") so'zlaridan kelib chiqqan — ya'ni bu a'zolar qorin pardasining orqasida, qorin
    bo'shlig'ining old qismidagi ichak a'zolaridan ajratilgan holda joylashgan. Bu joylashuv
    buyrakka jarrohlik yo'li bilan kirish (orqa yoki yon tomondan) usullarini belgilab beradi.
  </p>

  <div class="callout callout--note">
    <strong class="callout-title">Klinik eslatma</strong>
    Buyrak, siydik yo'li, qorin aortasi va pastki kovak vena kabi a'zolar
    <strong>"birlamchi retroperitoneal"</strong> tuzilmalar hisoblanadi — ular rivojlanish
    davomida doimo qorin parda orqasida qoladi. Bu, masalan, ichak a'zolaridan farqli
    o'laroq, ularga jarrohlik yo'li bilan kirishda muhim ahamiyatga ega.
  </div>
</section>

