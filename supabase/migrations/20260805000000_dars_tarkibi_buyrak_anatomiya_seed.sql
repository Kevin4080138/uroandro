  <h3>6.2. Fiziologik torayish nuqtalari</h3>
  <p>
    Siydik yo'lida uchta tabiiy torayish (<span class="en-term">narrowing</span>) joyi mavjud —
    bu joylar siydik toshlarining tiqilib qolishi uchun eng ko'p uchraydigan nuqtalardir:
  </p>
  <ol>
    <li><strong>Buyrak-siydik yo'li qo'shilish nuqtasi</strong> (<span class="en-term">ureteropelvic junction, UPJ</span>) — buyrak jomi siydik yo'liga o'tadigan joy.</li>
    <li><strong>Chov tomirlari bilan kesishgan joy</strong> — siydik yo'li umumiy chov arteriyasi/venasi ustidan o'tadigan nuqta.</li>
    <li><strong>Qovuqqa kirish nuqtasi</strong> (<span class="en-term">ureterovesical junction, UVJ</span>) — siydik yo'lining qovuq devoridan o'tib, qovuq ichiga ochiladigan joyi.</li>
  </ol>

  <div class="callout callout--note">
    <strong class="callout-title">Klinik eslatma</strong>
    Siydik yo'li qovuq devoridan <strong>qiyalik bilan</strong> o'tadi va qovuqning detruzor
    mushagi bilan birlashadi (Waldeyer pardasi). Bu mexanizm siydikning qovuqdan siydik
    yo'liga teskari oqib chiqishi — <strong>vezikoureteral reflyuks <span class="en-term">vesicoureteral
    reflux</span></strong>ning oldini oladi.
  </div>

  <h3>6.3. Mikroskopik tuzilishi</h3>
  <p>
    Siydik yo'li uch qatlamdan iborat:
  </p>
  <ul>
    <li><strong>Shilliq qavat <span class="en-term">mucosa</span></strong> — o'tish epiteliysi (urotelium) bilan qoplangan;</li>
    <li><strong>Mushak qavati <span class="en-term">muscularis</span></strong> — ikkita uzunlamasiga qavat va ular orasidagi dumaloq qavatdan iborat, peristaltik harakatni ta'minlaydi;</li>
    <li><strong>Tashqi qavat <span class="en-term">adventitia</span></strong> — biriktiruvchi to'qima, qon tomirlari va nervlarni saqlaydi.</li>
  </ul>

  <div class="callout callout--note">
    <strong class="callout-title">Yo'naltiruvchi</strong>
    Siydik yo'lining peristaltikasi <strong>kichik kosachalardagi "pacemaker" hujayralar</strong>
    tomonidan boshqariladi va asab tizimi nazoratidan nisbatan mustaqil ishlaydi — shuning
    uchun kesib olingan siydik yo'li qismi ham bir muddat o'z holicha qisqarishni davom
    ettirishi mumkin.
  </div>
