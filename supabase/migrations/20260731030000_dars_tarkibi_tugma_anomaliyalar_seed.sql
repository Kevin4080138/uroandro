          rentgen bilan tekshirish. Ammo bu nurlanish manbayi bo'lganligi uchun, bolalarda takroriy
          baholash uchun <span class="en-term">radionuklid sistografiya (RNC)</span> afzal ko'rilishi mumkin.
        </p>
      </div>
    </div>
